public class Q24_ShiftOperator {
    public static void main(String[] args) {
        int a = 16;
        int b = -16;
        System.out.println("a << 2 = " + (a << 2));
        System.out.println("a >> 2 = " + (a >> 2));
        System.out.println("b >> 2 = " + (b >> 2));
        System.out.println("b >>> 28 = " + (b >>> 28));
    }
}
